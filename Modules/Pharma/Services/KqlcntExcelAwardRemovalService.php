<?php

namespace Modules\Pharma\Services;

use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;
use Illuminate\Validation\ValidationException;
use Modules\Muasamcong\Models\KqlcntAwardItem;
use Modules\Pharma\Models\DrugBidAward;

/**
 * Destructive operations for Excel-only KQLCNT groups. Fail closed on mixed
 * provenance, shared TBMT scopes and downstream business documents.
 */
final class KqlcntExcelAwardRemovalService
{
    public function reset(int $itemId, int $actorId): void
    {
        DB::transaction(function () use ($itemId, $actorId): void {
            [$lines, $awards, $notice] = $this->lockedGroup($itemId);
            $this->assertNoDownstream($awards);
            if ($awards->isEmpty()) {
                $this->reject('Hồ sơ chưa liên kết sản phẩm Pharma để reset.');
            }

            $this->clearSetup($awards->pluck('id')->all(), $notice);

            Log::info('KQLCNT Excel setup reset', ['notice' => $notice, 'actor_id' => $actorId, 'canonical_ids' => $lines->pluck('id')->all(), 'pharma_ids' => $awards->pluck('id')->all()]);
        }, 3);
    }

    /**
     * Read-only display hint. Mutation endpoints always revalidate in a transaction.
     */
    public function hasSetup(int $itemId): bool
    {
        $item = KqlcntAwardItem::query()->findOrFail($itemId);
        $ids = DrugBidAward::query()->where('bidding_notice_code', $item->notify_no)->pluck('id')->all();

        return $this->setupExists($ids, (string) $item->notify_no);
    }

    private function clearSetup(array $ids, string $notice): void
    {
            $resultKey = 'tbmt:'.$notice;
            DB::table('pharma_drug_bid_award_management_assignments')->whereIn('drug_bid_award_id', $ids)->delete();
            DB::table('pharma_drug_bid_award_commercial_assignments')->whereIn('drug_bid_award_id', $ids)->delete();
            DB::table('pharma_drug_bid_award_product_policies')->whereIn('drug_bid_award_id', $ids)->delete();
            DB::table('pharma_drug_bid_award_allocations')->whereIn('drug_bid_award_id', $ids)->delete();

            $scopeIds = DB::table('pharma_drug_bid_award_distribution_scopes')->where('result_key', $resultKey)->pluck('id');
            DB::table('pharma_drug_bid_award_distribution_scope_partners')->whereIn('distribution_scope_id', $scopeIds)->delete();
            DB::table('pharma_drug_bid_award_distribution_scope_provinces')->whereIn('distribution_scope_id', $scopeIds)->delete();
            DB::table('pharma_drug_bid_award_distribution_scopes')->whereIn('id', $scopeIds)->delete();
            DB::table('pharma_drug_bid_award_commercial_policies')->where('result_key', $resultKey)->delete();

    }

    public function delete(int $itemId, int $actorId): void
    {
        DB::transaction(function () use ($itemId, $actorId): void {
            [$lines, $awards, $notice] = $this->lockedGroup($itemId);
            $this->assertNoDownstream($awards);
            $ids = $awards->pluck('id')->all();
            // Only delete provenance generated by the exact Excel canonical group.
            // Refuse historical/manual Pharma rows with independent source records.
            if (DB::table('pharma_drug_bid_award_sources')->whereIn('drug_bid_award_id', $ids)->exists()) {
                $this->reject('Có dữ liệu nguồn Pharma khác; không thể xóa tự động.');
            }
            // Reset and delete are atomic: no intermediate unconfigured state
            // becomes visible if a later deletion fails.
            if ($this->setupExists($ids, $notice)) {
                $this->clearSetup($ids, $notice);
            }
            $this->assertEmptySetup($ids, $notice);
            DB::table('pharma_drug_bid_award_matches')->whereIn('drug_bid_award_id', $ids)->delete();
            DB::table('pharma_drug_bid_awards')->whereIn('id', $ids)->delete();
            KqlcntAwardItem::query()->whereIn('id', $lines->pluck('id'))->delete();

            Log::warning('KQLCNT Excel permanently deleted', ['notice' => $notice, 'actor_id' => $actorId, 'canonical_ids' => $lines->pluck('id')->all(), 'pharma_ids' => $ids]);
        }, 3);
    }

    private function lockedGroup(int $itemId): array
    {
        $item = KqlcntAwardItem::query()->whereKey($itemId)->lockForUpdate()->firstOrFail();
        $notice = trim((string) $item->notify_no);
        if ($notice === '' || trim((string) $item->contractor_code) === '') {
            $this->reject('Hồ sơ thiếu mã TBMT hoặc mã nhà thầu.');
        }

        $lines = KqlcntAwardItem::query()->where('notify_no', $notice)
            ->where('contractor_code', $item->contractor_code)
            ->where('contractor_name', $item->contractor_name)
            ->lockForUpdate()->get();
        if ($lines->isEmpty() || $lines->contains(fn ($line) => $line->source !== 'excel' || $line->synced_from_catalog_at === null)) {
            $this->reject('Chỉ cho phép thao tác với hồ sơ import Excel thuần.');
        }

        // Legacy scopes are TBMT-wide: never mutate if another contractor
        // or another Pharma product shares the same notice.
        if (KqlcntAwardItem::query()->where('notify_no', $notice)->whereNotIn('id', $lines->pluck('id'))->exists()) {
            $this->reject('TBMT có nhiều nhóm nhà thầu hoặc nguồn dữ liệu khác.');
        }

        $canonicalIds = $lines->pluck('id')->all();
        $awards = DrugBidAward::query()->where('bidding_notice_code', $notice)->lockForUpdate()->get();
        if (($awards->isNotEmpty() && $awards->count() !== $lines->count())
            || $awards->contains(fn ($award) => $award->source_type !== DrugBidAward::SOURCE_MUASAMCONG
                || ! in_array((int) $award->source_id, $canonicalIds, true))
            || $awards->pluck('source_id')->unique()->count() !== $awards->count()) {
            $this->reject('Liên kết Pharma không thuần Excel hoặc không duy nhất.');
        }

        return [$lines, $awards, $notice];
    }

    private function assertNoDownstream($awards): void
    {
        $ids = $awards->pluck('id')->all();
        $allocations = DB::table('pharma_drug_bid_award_allocations')->whereIn('drug_bid_award_id', $ids)->pluck('id')->all();
        foreach (['pharma_inventory_issue_items', 'pharma_inventory_issue_commissions', 'pharma_inventory_issue_deferred_supplies', 'pharma_price_list_item_bid_evidence'] as $table) {
            if (DB::table($table)->whereIn('drug_bid_award_id', $ids)->exists()) {
                $this->reject('Hồ sơ đã có chứng từ hoặc dữ liệu nghiệp vụ phụ thuộc ('.$table.').');
            }
        }
        if (DB::table('pharma_drug_bid_award_contracts')->whereIn('drug_bid_award_allocation_id', $allocations)->exists()) {
            $this->reject('Phân bổ đã có hợp đồng; không thể reset hoặc xóa.');
        }
        foreach (['pharma_inventory_issue_items', 'pharma_inventory_issue_commissions', 'pharma_inventory_issue_deferred_supplies'] as $table) {
            if (DB::table($table)->whereIn('drug_bid_award_allocation_id', $allocations)->exists()) {
                $this->reject('Đã có phiếu xuất kho tham chiếu phân bổ.');
            }
        }
    }

    private function setupExists(array $ids, string $notice): bool
    {
        foreach (['pharma_drug_bid_award_allocations', 'pharma_drug_bid_award_product_policies', 'pharma_drug_bid_award_management_assignments', 'pharma_drug_bid_award_commercial_assignments'] as $table) {
            if (DB::table($table)->whereIn('drug_bid_award_id', $ids)->exists()) {
                return true;
            }
        }

        foreach (['pharma_drug_bid_award_distribution_scopes', 'pharma_drug_bid_award_commercial_policies'] as $table) {
            if (DB::table($table)->where('result_key', 'tbmt:'.$notice)->exists()) {
                return true;
            }
        }

        return false;
    }

    private function assertEmptySetup(array $ids, string $notice): void
    {
        foreach (['pharma_drug_bid_award_allocations', 'pharma_drug_bid_award_product_policies', 'pharma_drug_bid_award_management_assignments', 'pharma_drug_bid_award_commercial_assignments'] as $table) {
            if (DB::table($table)->whereIn('drug_bid_award_id', $ids)->exists()) {
                $this->reject('Phải reset toàn bộ phân bổ và chính sách trước khi xóa.');
            }
        }
        foreach (['pharma_drug_bid_award_distribution_scopes', 'pharma_drug_bid_award_commercial_policies'] as $table) {
            if (DB::table($table)->where('result_key', 'tbmt:'.$notice)->exists()) {
                $this->reject('Phải reset phạm vi phân bổ và chính sách cấp TBMT trước khi xóa.');
            }
        }
    }

    private function reject(string $message): never
    {
        throw ValidationException::withMessages(['award' => $message]);
    }
}
